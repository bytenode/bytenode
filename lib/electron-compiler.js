'use strict';

const { spawn } = require('child_process');
const fs = require('fs');
const path = require('path');
const { brotliCompressSync } = require('zlib');

function removeDirectory (directory) {
  if (!fs.existsSync(directory)) return;
  for (const entry of fs.readdirSync(directory)) {
    const entryPath = path.join(directory, entry);
    if (fs.lstatSync(entryPath).isDirectory()) removeDirectory(entryPath);
    else fs.unlinkSync(entryPath);
  }
  fs.rmdirSync(directory);
}

function createElectronCompiler (debug) {
  const DEBUG = debug;
/**
 * This function runs the compileCode() function (above)
 * via a child process using Electron as Node
 * @param {string} javascriptCode
 * @param {object} [options] - optional options object
 * @param {string} [options.electronPath] - optional path to Electron executable, defaults to the installed node_modules/electron
 * @param {boolean} [options.compress]
 * @returns {Promise<Buffer>} - returns a Promise which resolves in the generated bytecode.
 */
const compileElectronCode = function (javascriptCode, options) {
  return new Promise((resolve, reject) => {
    function onEnd () {
      if (options.compress) data = brotliCompressSync(data);

      resolve(data);
    }

    options = options || {};

    let data = Buffer.from([]);

    // Resolve `electron` lazily and only when no explicit path was given. This lets
    // consumers (e.g. a linked/forked bytenode living outside the project's node_modules,
    // where `require('electron')` would not resolve) pass `electronPath` instead.
    const electronPath = options.electronPath
      ? path.normalize(options.electronPath)
      : /** @type {string} */ (require('electron'));
    if (!fs.existsSync(electronPath)) {
      throw new Error('Electron not found');
    }
    const bytenodePath = path.join(__dirname, 'cli.js');

    // create a subprocess in which we run Electron as our Node and V8 engine
    // running Bytenode to compile our code through stdin/stdout
    const child = spawn(electronPath, [bytenodePath, '--compile', '--no-module', '-'], {
      env: { ELECTRON_RUN_AS_NODE: '1' },
      stdio: ['pipe', 'pipe', 'pipe', 'ipc']
    });

    if (child.stdin) {
      child.stdin.write(javascriptCode);
      child.stdin.end();
    }

    if (child.stdout) {
      child.stdout.on('data', (chunk) => {
        data = Buffer.concat([data, chunk]);
      });
      child.stdout.on('error', (err) => {
        console.error(err);
      });
      child.stdout.on('end', onEnd);
    }

    if (child.stderr) {
      child.stderr.on('data', (chunk) => {
        console.error('Error: ', chunk.toString());
      });
      child.stderr.on('error', (err) => {
        console.error('Error: ', err);
      });
    }

    child.addListener('message', (message) => console.log(message));
    child.addListener('error', err => console.error(err));

    child.on('error', (err) => reject(err));
    child.on('exit', onEnd);
  });
};

/**
 * Compiles code to bytecode inside an actual Electron *main* process (NOT
 * ELECTRON_RUN_AS_NODE). This is required on Electron >= 42 (V8 >= 14.8): the
 * main/browser process boots from Chromium's `v8_context_snapshot`, whose
 * read-only heap differs from the Node default snapshot used by
 * ELECTRON_RUN_AS_NODE. Bytecode carries a read-only-snapshot checksum
 * (header offset 16); if it was produced under run-as-node it will not match
 * the main process at load time, and V8 14.8 hard-aborts (SIGTRAP) while
 * deserializing instead of cleanly rejecting. Compiling here, in the same
 * process type that will later load the .jsc, makes the checksum match.
 * @param {string} javascriptCode
 * @param {object} [options]
 * @param {string} [options.electronPath]
 * @param {boolean} [options.compress]
 * @returns {Promise<Buffer>}
 */
const compileElectronMainCode = function (javascriptCode, options) {
  return new Promise((resolve, reject) => {
    options = options || {};

    const os = require('os');

    const electronPath = options.electronPath
      ? path.normalize(options.electronPath)
      : /** @type {string} */ (require('electron'));
    if (!fs.existsSync(electronPath)) {
      throw new Error('Electron not found');
    }

    const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'bytenode-electron-main-'));
    const inFile = path.join(tmpDir, 'input.js');
    const outFile = path.join(tmpDir, 'output.jsc');
    const compilerScript = path.join(tmpDir, 'compiler.js');

    fs.writeFileSync(inFile, javascriptCode);

    // Minimal Electron main-process entry: wait for app ready, compile, write,
    // then quit. No BrowserWindow is created. The V8 flags must match those set
    // by bytenode when the .jsc is later loaded, so the flag hash agrees.
    const compilerSource = [
      "const { app } = require('electron');",
      "const fs = require('fs');",
      "const vm = require('vm');",
      "const v8 = require('v8');",
      "v8.setFlagsFromString('--no-lazy');",
      "v8.setFlagsFromString('--no-flush-bytecode');",
      // No renderer/window is created, so the Chromium sandbox is irrelevant here.
      // Disabling it avoids failures when Electron is launched as root in CI containers.
      'if (typeof app.disableHardwareAcceleration === "function") app.disableHardwareAcceleration();',
      'function run () {',
      '  try {',
      '    const code = fs.readFileSync(' + JSON.stringify(inFile) + ", 'utf-8');",
      '    const script = new vm.Script(code, { produceCachedData: true });',
      '    const buf = (script.createCachedData && script.createCachedData.call) ? script.createCachedData() : script.cachedData;',
      '    fs.writeFileSync(' + JSON.stringify(outFile) + ', buf);',
      // Use app.exit(code) rather than `process.exitCode = code; app.quit()`:
      // app.quit() runs the graceful-shutdown path and does NOT propagate
      // process.exitCode, so a failed compile would otherwise exit 0 and the
      // parent would misreport the real error as a missing-output-file ENOENT.
      '    app.exit(0);',
      '  } catch (err) {',
      '    process.stderr.write(String((err && err.stack) || err) + "\\n");',
      '    app.exit(1);',
      '  }',
      '}',
      'app.whenReady().then(run);'
    ].join('\n');

    fs.writeFileSync(compilerScript, compilerSource);

    const cleanup = () => {
      try { removeDirectory(tmpDir); } catch (_) { /* ignore */ }
    };

    // Pass --no-sandbox on argv (not only via app.commandLine.appendSwitch in the
    // compiler script): the SUID/zygote sandbox initializes before the script runs,
    // so an in-script switch is too late and Electron aborts as root / in CI
    // containers. It must come BEFORE the script path so Electron treats it as a
    // switch rather than an argument to the app. No window is created here, so
    // disabling the sandbox is safe.
    // Deliberately remove ELECTRON_RUN_AS_NODE: we want the browser/main process.
    const env = Object.assign({}, process.env);
    delete env.ELECTRON_RUN_AS_NODE;
    const child = spawn(electronPath, ['--no-sandbox', compilerScript], {
      env,
      // Capture (don't inherit) the child's streams. A real Electron browser
      // process prints benign startup noise (GPU/Vulkan/deprecation warnings) to
      // stderr; inheriting it pollutes the caller's output and makes a genuine
      // compile error indistinguishable from chatter. We buffer both streams and
      // surface them only when they matter: folded into the rejection on failure,
      // or printed when BYTENODE_DEBUG is set.
      stdio: ['ignore', 'pipe', 'pipe']
    });

    let stdout = '';
    let stderr = '';
    if (child.stdout) {
      child.stdout.setEncoding('utf8');
      child.stdout.on('data', (chunk) => { stdout += chunk; });
    }
    if (child.stderr) {
      child.stderr.setEncoding('utf8');
      child.stderr.on('data', (chunk) => { stderr += chunk; });
    }

    child.on('error', (err) => { cleanup(); reject(err); });

    // Use 'close' (not 'exit'): 'exit' can fire before the stdout/stderr pipes
    // have fully drained, which would let us reject with a truncated/empty error
    // detail. 'close' fires only after all stdio streams have ended.
    child.on('close', (code, signal) => {
      if (DEBUG && (stdout || stderr)) {
        console.error('[bytenode] electronMain stdout:\n' + stdout);
        console.error('[bytenode] electronMain stderr:\n' + stderr);
      }
      if (code !== 0) {
        cleanup();
        const detail = stderr.trim() || stdout.trim();
        // On a signal kill (e.g. a sandbox abort) code is null; report the signal
        // so the failure isn't a misleading "exit code null".
        const how = signal ? 'signal ' + signal : 'exit code ' + code;
        reject(new Error(
          'Electron main-process bytecode compilation failed (' + how + ')' +
          (detail ? ':\n' + detail : '')
        ));
        return;
      }
      try {
        let data = fs.readFileSync(outFile);
        if (options.compress) data = brotliCompressSync(data);
        cleanup();
        resolve(data);
      } catch (err) {
        cleanup();
        reject(err);
      }
    });
  });
};

/**
 * Compiles code to bytecode inside an Electron *renderer* process, from a
 * preload script of a hidden BrowserWindow. Use this for code that will be
 * loaded in a preload script or a renderer page.
 *
 * Since Electron 43.5.1 the renderer's read-only snapshot no longer matches
 * the one used by ELECTRON_RUN_AS_NODE or by the main process, so bytecode
 * produced by compileElectronCode() or compileElectronMainCode() is rejected
 * there (cachedDataRejected). Bytecode produced here is renderer-only: it is
 * rejected in the main process and in worker threads.
 * @param {string} javascriptCode
 * @param {object} [options]
 * @param {string} [options.electronPath]
 * @param {boolean} [options.compress]
 * @returns {Promise<Buffer>}
 */
const compileElectronRendererCode = function (javascriptCode, options) {
  return new Promise((resolve, reject) => {
    options = options || {};

    const os = require('os');

    const electronPath = options.electronPath
      ? path.normalize(options.electronPath)
      : /** @type {string} */ (require('electron'));
    if (!fs.existsSync(electronPath)) {
      throw new Error('Electron not found');
    }

    const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'bytenode-electron-renderer-'));
    const inFile = path.join(tmpDir, 'input.js');
    const outFile = path.join(tmpDir, 'output.jsc');
    const mainScript = path.join(tmpDir, 'main.js');
    const preloadScript = path.join(tmpDir, 'preload.js');
    // A private userData dir per compile, so parallel compiles don't fight
    // over Chromium's SingletonLock (see #262).
    const userDataDir = path.join(tmpDir, 'user-data');

    fs.writeFileSync(inFile, javascriptCode);

    const mainSource = [
      "const { app, BrowserWindow, ipcMain } = require('electron');",
      'app.disableHardwareAcceleration();',
      "ipcMain.on('bytenode-done', (_event, err) => {",
      '  if (err) process.stderr.write(err + "\\n");',
      '  app.exit(err ? 1 : 0);',
      '});',
      'app.whenReady().then(() => {',
      '  const win = new BrowserWindow({',
      '    show: false,',
      '    webPreferences: {',
      '      preload: ' + JSON.stringify(preloadScript) + ',',
      '      nodeIntegration: true,',
      '      contextIsolation: false,',
      '      sandbox: false',
      '    }',
      '  });',
      "  win.webContents.on('render-process-gone', (_event, details) => {",
      "    process.stderr.write('renderer process gone: ' + details.reason + '\\n');",
      '    app.exit(2);',
      '  });',
      "  win.loadURL('about:blank');",
      '});'
    ].join('\n');

    // Requiring bytenode here sets --no-lazy / --no-flush-bytecode exactly as
    // they will be set when the .jsc is later loaded, so the flag hash agrees.
    const preloadSource = [
      "const { ipcRenderer } = require('electron');",
      'try {',
      '  require(' + JSON.stringify(path.join(__dirname, 'index.js')) + ');',
      "  const fs = require('fs');",
      "  const vm = require('vm');",
      '  const code = fs.readFileSync(' + JSON.stringify(inFile) + ", 'utf-8');",
      '  const script = new vm.Script(code, { produceCachedData: true });',
      '  fs.writeFileSync(' + JSON.stringify(outFile) + ', script.createCachedData());',
      "  ipcRenderer.send('bytenode-done');",
      '} catch (err) {',
      "  ipcRenderer.send('bytenode-done', String((err && err.stack) || err));",
      '}'
    ].join('\n');

    fs.writeFileSync(mainScript, mainSource);
    fs.writeFileSync(preloadScript, preloadSource);

    const cleanup = () => {
      try { removeDirectory(tmpDir); } catch (_) { /* ignore */ }
    };

    // --no-sandbox must be on argv: the Linux SUID sandbox check runs before
    // main.js, so app.commandLine.appendSwitch() is too late.
    const args = ['--no-sandbox', '--user-data-dir=' + userDataDir, mainScript];

    const env = Object.assign({}, process.env);
    delete env.ELECTRON_RUN_AS_NODE;

    const child = spawn(electronPath, args, { env, stdio: ['ignore', 'pipe', 'pipe'] });

    let output = '';
    child.stdout.on('data', (chunk) => { output += chunk; });
    child.stderr.on('data', (chunk) => { output += chunk; });

    child.on('error', (err) => { cleanup(); reject(err); });

    child.on('close', (code) => {
      try {
        if (code !== 0) {
          throw new Error('Electron renderer bytecode compilation failed (exit code ' + code + ')' +
            (output.trim() ? ':\n' + output.trim() : ''));
        }
        let data = fs.readFileSync(outFile);
        if (options.compress) data = brotliCompressSync(data);
        resolve(data);
      } catch (err) {
        reject(err);
      } finally {
        cleanup();
      }
    });
  });
};


  return { compileElectronCode, compileElectronMainCode, compileElectronRendererCode };
}

module.exports = createElectronCompiler;
